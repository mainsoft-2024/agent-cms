export type MessageParams = Record<string, string | number | null | undefined>;

/** Fill `{name}` placeholders. Unknown placeholders stay as they are. */
export function format(template: string, params: MessageParams = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (params[k] === undefined || params[k] === null ? m : String(params[k])));
}

/** A translator over a catalog (missing keys fall back to English). */
export function createT(messages: Partial<CmsMessages> = {}) {
  const all: CmsMessages = { ...en, ...messages };
  return (key: MessageKey, params?: MessageParams) => format(all[key] ?? key, params);
}

export type T = ReturnType<typeof createT>;

/**
 * What to show for a failed call: the server's message (already in the CMS's
 * language) for a CmsRemoteError, else a generic line.
 */
export function errorMessage(e: unknown, t: T): string {
  if (isCmsRemoteError(e)) return e.code === "network" || e.code === "http" ? t("error_generic") : e.message;
  return t("error_generic");
}
