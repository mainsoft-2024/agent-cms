export type MessageParams = Record<string, string | number | null | undefined>;

/** True when a word ends in a closed syllable, which decides the Korean particle after it (이/가, 을/를, 으로/로). */
export function endsClosed(word: string): boolean {
  const s = word.trim();
  const c = s.charCodeAt(s.length - 1);
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 !== 0;
  if (/\d$/.test(s)) return "013678".includes(s[s.length - 1]);
  // Latin words as they are usually read: "bot", "team", "Kim" are closed; "Jisu", "docs" are not.
  return /(?:[lmnbkpt]|ng|ck)$/i.test(s);
}

/**
 * Fill `{name}` placeholders. Unknown placeholders stay as they are.
 * `{name|이|가}` writes no value, only the particle that fits the value:
 * "{who}{who|이|가}" gives "김지수가" and "docs-bot이".
 */
export function format(template: string, params: MessageParams = {}): string {
  return template.replace(/\{(\w+)(?:\|([^|}]*)\|([^|}]*))?\}/g, (m, k: string, closed?: string, open?: string) => {
    const v = params[k];
    if (v === undefined || v === null) return closed === undefined ? m : "";
    if (closed === undefined) return String(v);
    const s = String(v).trim();
    const c = s.charCodeAt(s.length - 1);
    // "으로/로": a final ㄹ takes 로 ("서울로", "v7로").
    const rieul = (c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 === 8) || /[178l]$/i.test(s);
    return endsClosed(s) && !(closed === "으로" && rieul) ? closed : (open ?? "");
  });
}

/** A translator over a catalog (missing keys fall back to English). */
export function createT(messages: Partial<CmsMessages> = {}) {
  const all: CmsMessages = { ...en, ...messages };
  return (key: MessageKey, params?: MessageParams) => format(all[key] ?? key, params);
}

export type T = ReturnType<typeof createT>;

/**
 * What to show for a failed call: the server's message (already in the CMS's
 * language) for a CmsRemoteError, else a generic line.
 */
export function errorMessage(e: unknown, t: T): string {
  if (isCmsRemoteError(e)) return e.code === "network" || e.code === "http" ? t("error_generic") : e.message;
  return t("error_generic");
}
